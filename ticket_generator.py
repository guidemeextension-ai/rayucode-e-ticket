"""
E Ticket Promotion Code Generator
=================================
Place ticket_template.jpg beside this script, edit PROMO_CODES, then run:
    python3 ticket_generator.py

Install dependencies from requirements.txt first. The script uses the same
renderer as the web app and bot and creates one JPG per code in output/.
"""

from pathlib import Path

from ticket_core import TEMPLATE_PATH, generate_ticket

OUTPUT_DIR = Path("output")

PROMO_CODES = [
    "PROMO-A8K2P9",
    "PROMO-B4M7X1",
    "PROMO-C9D3W6",
    "virak x mylove",
]


def main():
    if not TEMPLATE_PATH.is_file():
        print(f"ERROR: Could not find ticket template: {TEMPLATE_PATH}")
        print("Put your JPG ticket design in this folder and name it ticket_template.jpg.")
        return

    if not PROMO_CODES:
        print("ERROR: PROMO_CODES is empty. Add at least one promotion code.")
        return

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    print(f"Generating {len(PROMO_CODES)} ticket(s)...")

    for index, code in enumerate(PROMO_CODES, start=1):
        # Shared rendering keeps promo placement, QR payload, and JPEG settings
        # identical to tickets generated by the web app and Telegram bot.
        with generate_ticket(code) as ticket:
            output_path = OUTPUT_DIR / f"ticket_{index:03d}.jpg"
            output_path.write_bytes(ticket.getvalue())
        print(f"Created: {output_path}  |  Code: {code}")

    print("\nFinished! Check the output/ folder for your tickets.")


if __name__ == "__main__":
    main()
